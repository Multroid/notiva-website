/**
 * Rasterises the email images into public/email/ and writes the dimension
 * manifest src/lib/leads/email-assets.ts.
 *
 * Needed because the site's own assets are the wrong formats for mail: every
 * logo is an SVG (Gmail strips SVG entirely) and the Novi mascots are WebP
 * (Outlook on Windows cannot decode it). Both become PNG here.
 *
 * The mascots are also trimmed. The source WebPs carry a wide transparent
 * margin, which in an email renders as an unexplained gap above the artwork —
 * the mail client has no way to know the pixels are empty. trim() crops to the
 * real bounding box, so the declared width/height is all mascot.
 *
 * Because trimming changes each image's aspect ratio, the true output size is
 * written to a generated manifest rather than hardcoded in the template. That
 * keeps width/height attributes exact, which matters: they are what stops the
 * layout collapsing in clients that block images by default.
 *
 *   node scripts/build-email-assets.mjs
 *
 * Re-run only when the source art changes; the output is committed so a build
 * never depends on this script.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const OUT = 'public/email';
const MANIFEST = 'src/lib/leads/email-assets.ts';

/* Retina: rendered at 2x the display width, constrained to it in the markup. */
const SCALE = 2;

/** [source, output, display width, trim transparent edges] */
const JOBS = [
	['public/notiva/notiva-logo-chip.svg', 'notiva-logo.png', 34, false],
	['public/notiva/novi/react-wave.webp', 'novi-wave.png', 150, true],
	['public/notiva/novi/thankful.webp', 'novi-thankful.png', 168, true],
	['public/notiva/novi/hold-doc.webp', 'novi-hold-doc.png', 168, true],
];

await fs.mkdir(OUT, { recursive: true });

const manifest = {};

for (const [src, out, displayWidth, doTrim] of JOBS) {
	const target = path.join(OUT, out);
	const isSvg = src.endsWith('.svg');

	/* density, not resize-up: rendering the SVG at the target raster size keeps
	   the curves clean instead of upscaling a 600px bitmap. */
	let pipeline = isSvg ? sharp(src, { density: 384 }) : sharp(src);
	if (doTrim) pipeline = pipeline.trim();

	const info = await pipeline
		.resize({ width: displayWidth * SCALE, fit: 'inside', withoutEnlargement: !isSvg })
		.png({ compressionLevel: 9, palette: true })
		.toFile(target);

	/* Halve the real output back to display size; round rather than assume, since
	   fit:'inside' may land a pixel off on odd aspect ratios. */
	const w = Math.round(info.width / SCALE);
	const h = Math.round(info.height / SCALE);
	manifest[out] = { w, h };

	console.log(
		`${out.padEnd(20)} ${info.width}x${info.height} → display ${w}x${h}  ${(info.size / 1024).toFixed(1)} kB${doTrim ? '  (trimmed)' : ''}`
	);
}

const body = `/* GENERATED by scripts/build-email-assets.mjs — do not edit by hand.
 *
 * Display dimensions of the PNGs in public/email/. The templates put these on
 * every <img> as width/height so the layout holds even when a client blocks
 * images, and so trimmed artwork keeps its true aspect ratio. */
export const EMAIL_ASSETS = ${JSON.stringify(manifest, null, 1).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")} as const;

export type EmailAsset = keyof typeof EMAIL_ASSETS;
`;

await fs.writeFile(MANIFEST, body);
console.log(`\nwrote ${JOBS.length} PNGs to ${OUT}/ and the manifest to ${MANIFEST}`);
