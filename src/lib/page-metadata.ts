/* Per-page Metadata builder.
 *
 * Every indexable route needs the same six things — title, description,
 * canonical, Open Graph, Twitter card, and a German locale — and getting one of
 * them subtly wrong on one page is the usual failure mode. So they are built
 * from one place.
 *
 * Two site-specific rules are baked in and should not be worked around:
 *
 *  1. ONE URL SERVES TWO LANGUAGES. German is server-rendered; English is a
 *     client-side toggle (`notiva.lang` in localStorage) at the *same* URL.
 *     Crawlers therefore only ever see German, so every string passed here is
 *     German and `og:locale` is `de_DE`. There is deliberately no `hreflang` /
 *     `alternates.languages`: `/de` and `/en` do not exist, and pointing at
 *     URLs that 404 is worse than shipping no alternates at all.
 *
 *  2. THE TITLE MUST MATCH WHAT THE CLIENT SETS. `useNotivaTitle` installs a
 *     MutationObserver that re-asserts `document.title` after hydration, so the
 *     `title` given here has to be character-identical to that hook's German
 *     argument on the same route. If they drift, the SSR title and the rendered
 *     title disagree and Google indexes the second one.
 *
 * The `images` handling is the one non-obvious part; see SITE_OG_IMAGE below.
 */

import type { Metadata } from 'next';

import { SITE_URL, absoluteUrl } from './structured-data';

const SITE_NAME = 'Notiva';

/* The site-wide card generated by `src/app/opengraph-image.tsx`.
 *
 * It has to be restated here rather than inherited. Next merges a file-based
 * `opengraph-image` into the metadata of the segment that *contains* the file,
 * but a segment declaring its own `openGraph` replaces the inherited object
 * wholesale (`mergeMetadata` → `case 'openGraph'`) — so a page three segments
 * below `app/` that sets `openGraph` silently drops the root card. Verified by
 * grepping the built HTML: without this, `/`, `/for-investors` and `/support`
 * shipped no `og:image` at all while `/basket` (which declares no `openGraph`)
 * did.
 *
 * `/opengraph-image` is the real route Next emits for that file; the `?<hash>`
 * Next appends when it writes the tag itself is only a cache buster.
 *
 * `alt` mirrors the `alt` export of `src/app/opengraph-image.tsx`. It is copied
 * rather than imported because importing that module would pull `next/og` and
 * the whole ImageResponse tree into every page's module graph. */
const SITE_OG_IMAGE = {
	url: '/opengraph-image',
	width: 1200,
	height: 630,
	alt: 'Notiva — Nie wieder Angst vor dem Finanzamt. Das KI-native Finanz-Backoffice für Selbstständige in Deutschland.',
} as const;

export interface PageMetadataInput {
	/** Exactly the `<title>` text, German. Must equal the `useNotivaTitle` DE arg. */
	title: string;
	/** German, ~150–160 characters, benefit-led, honest that launch is 2026. */
	description: string;
	/** Route path with a leading slash, e.g. `'/support'`. Drives canonical + `og:url`. */
	path: string;
	/**
	 * Set on a page that sits in the *same* segment as the layout declaring a
	 * `title.template`. A template applies to child segments only, so without
	 * `absolute` the next template up (the root layout's `"Notiva - %s"`) wraps
	 * the title instead. Layouts and pages in nested segments leave this off and
	 * pass through the (notiva) group's identity template `'%s'`.
	 */
	absoluteTitle?: boolean;
	/**
	 * Set when this route segment ships its own `opengraph-image` file — today
	 * only `/merch/[slug]`. Leaving `images` unset lets Next merge that
	 * segment's generated card in; setting it would pin the generic site card
	 * over the per-product one.
	 */
	hasOwnOgImage?: boolean;
}

export function pageMetadata({
	title,
	description,
	path,
	absoluteTitle = false,
	hasOwnOgImage = false,
}: PageMetadataInput): Metadata {
	const url = absoluteUrl(path);
	const images = hasOwnOgImage ? undefined : [SITE_OG_IMAGE];

	return {
		title: absoluteTitle ? { absolute: title } : title,
		description,
		alternates: { canonical: path },
		openGraph: {
			type: 'website',
			locale: 'de_DE',
			siteName: SITE_NAME,
			title,
			description,
			url,
			/* Must stay absent (not `undefined`) when the segment has its own
			   card: Next's merge tests `hasOwnProperty('images')`, so an explicit
			   `images: undefined` would block the file-based image just as an
			   array would. Hence the spread rather than `images`. */
			...(images ? { images } : {}),
		},
		twitter: {
			card: 'summary_large_image',
			title,
			description,
			...(images ? { images } : {}),
		},
	};
}

/** Canonical origin, re-exported so page files need one import, not two. */
export { SITE_URL };

/** Keeps a route out of every index: `/basket` (per-visitor state) and the 404s. */
export const NOINDEX: NonNullable<Metadata['robots']> = {
	index: false,
	follow: false,
};
