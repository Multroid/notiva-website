-- Unsubscribe support for the waitlist.
--
-- unsubscribed_at already existed (and POST /api/waitlist already treats a
-- previously unsubscribed address as needing fresh consent), but there was no
-- way for a recipient to actually set it — every email footer promised an
-- unsubscribe that did not exist. DSGVO Art. 7(3) requires withdrawing consent
-- to be as easy as giving it, so this is not optional.
--
-- A separate token from confirm_token, deliberately:
--   - confirm_token expires after 14 days; an unsubscribe link has to keep
--     working for as long as the recipient still has the email, i.e. forever.
--   - single purpose per credential. Leaking one must not grant the other.
--
-- Generated by a column DEFAULT rather than in application code, so no insert
-- path can ever forget it and leave a row that cannot be unsubscribed.
-- translate() maps standard base64 to base64url: + → -, / → _, and = is dropped
-- because it has no replacement character.

alter table public.waitlist_signup
	add column if not exists unsubscribe_token text
		default translate(encode(gen_random_bytes(32), 'base64'), '+/=', '-_');

-- Existing rows predate the default and would otherwise be null.
update public.waitlist_signup
   set unsubscribe_token = translate(encode(gen_random_bytes(32), 'base64'), '+/=', '-_')
 where unsubscribe_token is null;

alter table public.waitlist_signup
	alter column unsubscribe_token set not null;

create unique index if not exists waitlist_signup_unsubscribe_token_key
	on public.waitlist_signup (unsubscribe_token);

comment on column public.waitlist_signup.unsubscribe_token is
	'Stable, non-expiring. Used by GET/POST /api/waitlist/unsubscribe and by the List-Unsubscribe header.';
comment on column public.waitlist_signup.unsubscribed_at is
	'Suppression marker. The row is kept rather than deleted so the opt-out is provable and a later signup requires fresh consent.';
